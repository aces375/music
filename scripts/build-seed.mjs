// Generates supabase/seed.sql from the sample documents and the sample traceability rows,
// after checking that every clause quoted in the rows appears verbatim in its document.
//   node scripts/build-seed.mjs          → write seed.sql
//   node scripts/build-seed.mjs --check  → verify only

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { SAMPLE_DOCUMENTS, SAMPLE_ROWS, markdownToText } from "../public/assets/sample-data.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");

/* ---------- verify ---------- */
const bodies = {};
for (const d of SAMPLE_DOCUMENTS) bodies[d.document_id] = readFileSync(join(root, "public", d.file), "utf8");

const squash = (s) => s.replace(/\s+/g, " ");
const problems = [];
for (const r of SAMPLE_ROWS) {
  const text = squash(markdownToText(bodies[r.document_id] || ""));
  if (!text.includes(squash(r.clause_text))) problems.push(`${r.obligation_id} (${r.document_id} ${r.clause_ref}) clause text not found in document`);
}
const ids = SAMPLE_ROWS.map((r) => r.obligation_id);
if (new Set(ids).size !== ids.length) problems.push("Duplicate obligation ids");
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
console.log(`✓ ${SAMPLE_ROWS.length} obligations verified against ${SAMPLE_DOCUMENTS.length} documents`);
if (checkOnly) process.exit(0);

/* ---------- generate ---------- */
// Deterministic UUIDs so regenerating the seed produces a stable diff.
function uuid(name) {
  const h = createHash("sha1").update(`clausemap:${name}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 3) | 8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const values = (rows) => rows.map((r) => `  (${r.map(q).join(", ")})`).join(",\n");
const insert = (table, cols, rows) => (rows.length ? `insert into ${table} (${cols.join(", ")}) values\n${values(rows)};\n` : "");

const docs = SAMPLE_DOCUMENTS.map((d) => [
  uuid(d.document_id), d.document_id, d.title, d.document_type, d.repository, d.file, d.counterparty, d.effective_date, bodies[d.document_id],
]);

const clauseKey = (r) => `${r.document_id}|${r.clause_ref}`;
const clauses = [...new Map(SAMPLE_ROWS.map((r) => [clauseKey(r), [uuid(clauseKey(r)), uuid(r.document_id), r.clause_ref, r.clause_text]])).values()];

const obligations = SAMPLE_ROWS.map((r) => {
  const [cmp, val, unit, freq] = r.target_parts || [];
  return [
    uuid(r.obligation_id), r.obligation_id, uuid(clauseKey(r)), r.obligation, r.obligation_type,
    cmp ?? null, val ?? null, unit ?? null, freq ?? null, r.target,
    r.coverage === "gap" ? r.gap_reason : null, r.clause_text, r.confidence, "manual", "confirmed",
  ];
});

const systemOf = (s) => s.split("→").pop().trim().split(/[ .]/)[0];
const mapped = SAMPLE_ROWS.filter((r) => r.metric_name);
const sources = [...new Map(mapped.map((r) => [r.data_source, [uuid(`ds:${r.data_source}`), r.data_source, systemOf(r.data_source), r.data_source]])).values()];
const metrics = [...new Map(mapped.map((r) => [r.metric_name, [uuid(`m:${r.metric_name}`), r.metric_name, r.platform, r.dashboard, uuid(`ds:${r.data_source}`)]])).values()];
const mappings = mapped.map((r) => [
  uuid(`map:${r.obligation_id}`), uuid(r.obligation_id), uuid(`m:${r.metric_name}`), r.coverage,
  r.coverage === "partial" ? r.gap_reason : null, r.confidence, r.coverage === "tracked" ? "confirmed" : "proposed",
]);
const evidence = mapped.flatMap((r) =>
  r.evidence.map((e, i) => [uuid(`ev:${r.obligation_id}:${i}`), uuid(`map:${r.obligation_id}`), e.kind, e.label, e.captured_at]),
);

const sql = `-- GENERATED by scripts/build-seed.mjs from public/assets/sample-data.js and public/samples/*.md.
-- Do not edit by hand: change the sources and run \`npm run seed\`.
-- Loads the three fictional sample documents and their ${SAMPLE_ROWS.length} obligations.

begin;

${insert("documents", ["id", "document_code", "title", "document_type", "repository", "source_url", "counterparty", "effective_date", "body"], docs)}
${insert("clauses", ["id", "document_id", "clause_ref", "text"], clauses)}
${insert("obligations", ["id", "obligation_code", "clause_id", "title", "obligation_type", "target_comparator", "target_value", "target_unit", "frequency", "target_text", "gap_note", "source_quote", "confidence", "extracted_by", "review_status"], obligations)}
${insert("data_sources", ["id", "name", "system", "lineage"], sources)}
${insert("metrics", ["id", "name", "platform", "dashboard", "data_source_id"], metrics)}
${insert("mappings", ["id", "obligation_id", "metric_id", "coverage", "gap_reason", "confidence", "status"], mappings)}
${insert("evidence", ["id", "mapping_id", "kind", "label", "captured_at"], evidence)}
commit;
`;

writeFileSync(join(root, "supabase", "seed.sql"), sql);
console.log(`✓ wrote supabase/seed.sql (${docs.length} documents, ${clauses.length} clauses, ${metrics.length} metrics, ${mappings.length} mappings, ${evidence.length} evidence)`);
